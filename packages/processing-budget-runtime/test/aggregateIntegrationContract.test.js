"use strict"

const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const test = require("node:test")

const packageRoot = path.resolve(__dirname, "..")
const repositoryRoot = path.resolve(packageRoot, "..", "..")
const source = (relativePath) => fs.readFileSync(path.join(repositoryRoot, relativePath), "utf8")

test("both wrappers expose operation and target reservations plus atomic workbook budgeting", () => {
  for (const extension of ["bob-bazaar-review", "bob-code-consistency-review"]) {
    const wrapper = source(`extensions/${extension}/src/sharedProcessingBudgetRuntime.ts`)
    assert.match(wrapper, /reserve\(category: SharedOperationScopedProcessingBudgetCategory/)
    assert.match(wrapper, /reserveForTarget\(category: SharedTargetScopedProcessingBudgetCategory/)
    assert.match(wrapper, /commitWorkbookBudget/)
    assert.match(wrapper, /commitXlsxWorkbookBudget/)
    assert.match(wrapper, /assertParsedXlsxWorkbookWithinBudget/)
    assert.match(wrapper, /sheets_per_workbook/)
    assert.match(wrapper, /rows_per_sheet/)
  }
})

test("Bazaar uses one operation ledger for count, source bytes, archive expansion, sheets, and rows", () => {
  const coordinator = source("extensions/bob-bazaar-review/src/ruleAuthoring/extraction/documentExtractor.ts")
  const fingerprint = source("extensions/bob-bazaar-review/src/ruleAuthoring/ruleSourceHash.ts")
  const docx = source("extensions/bob-bazaar-review/src/ruleAuthoring/extraction/docxExtractor.ts")
  const xlsx = source("extensions/bob-bazaar-review/src/ruleAuthoring/extraction/xlsxExtractor.ts")
  assert.match(coordinator, /ledger\.reserve\("document_count", requests\.length\)/)
  assert.match(coordinator, /maximumBytes: effectiveLimits\.maxSourceBytes,\s*ledger/)
  assert.match(coordinator, /budgetLedger: context\.ledger/)
  assert.doesNotMatch(coordinator, /preflightOoxmlArchive\(absolutePath/)
  assert.match(fingerprint, /options\.ledger \?\? new ProcessingBudgetLedger/)
  assert.match(docx, /context\.budgetLedger \?\? readLedger/)
  assert.match(xlsx, /commitXlsxWorkbookBudget/)
  assert.match(xlsx, /assertParsedXlsxWorkbookWithinBudget/)
  assert.ok(xlsx.indexOf("commitXlsxWorkbookBudget({") < xlsx.indexOf("readExcelFile.default"))
  assert.ok(xlsx.indexOf("readExcelFile.default") < xlsx.lastIndexOf("assertParsedXlsxWorkbookWithinBudget("))
  assert.doesNotMatch(xlsx, /\.slice\(0, .*maxWorkbookSheets/)
})

test("Consistency uses one operation ledger and hard-fails aggregate limit errors", () => {
  const coordinator = source("extensions/bob-code-consistency-review/src/analyzers/documentExtractor.ts")
  const xlsx = source("extensions/bob-code-consistency-review/src/analyzers/documentXlsxExtractor.ts")
  assert.match(coordinator, /const ledger = documentLedger\(limits, options\.processingBudgetLimits\)/)
  assert.match(coordinator, /const documentCount = countSelectedDocuments\(reviewInput\)/)
  assert.match(coordinator, /ledger\.reserve\("document_count", documentCount\)\.commit\(\)/)
  assert.doesNotMatch(coordinator, /ledger\.reserve\("document_count", 1\)/)
  assert.match(coordinator, /throwIfCancelled\(options\.signal\)/)
  assert.match(coordinator, /if \(options\.signal\?\.aborted\) throw cancellationReason\(options\.signal\)/)
  assert.match(coordinator, /if \(isResourceControlError\(error\)\) throw error/)
  assert.match(coordinator, /code\.startsWith\("bounded_document_"\)/)
  assert.match(coordinator, /code\.startsWith\("archive_"\)/)
  assert.match(coordinator, /code\.startsWith\("xlsx_"\)/)
  assert.match(coordinator, /\{ ledger, workbookTarget: workbookTarget\(filePath\), archive, signal \}/)
  assert.match(xlsx, /commitXlsxWorkbookBudget/)
  assert.match(xlsx, /assertParsedXlsxWorkbookWithinBudget/)
  assert.match(xlsx, /rowsToBudget: \(sheet\) => Math\.max\(0, sheet\.rows - 1\)/)
  assert.ok(xlsx.indexOf("commitXlsxWorkbookBudget({") < xlsx.indexOf("readExcelFile.default"))
  assert.ok(xlsx.indexOf("readExcelFile.default") < xlsx.lastIndexOf("assertParsedXlsxWorkbookWithinBudget("))
  assert.doesNotMatch(xlsx, /Math\.min\(dataRows\.length, limits\.maxRowsPerSheet\)/)
})
